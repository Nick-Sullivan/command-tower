// Regenerates every app icon file from tool/app_icon/app_icon.dart:
//
//   flutter test tool/app_icon/generate_icons_test.dart
//
// Run from the repo root. (It's a test only so it can use Flutter's canvas;
// CI's `flutter test` only runs test/, so it never runs there.)
import 'dart:io';
import 'dart:ui';

import 'package:flutter_test/flutter_test.dart';
import 'package:image/image.dart' as img;

import 'app_icon.dart';

const _design = 1024.0;

/// Square outputs (iOS, Play Store, pre-Android-8 launchers) show the whole
/// canvas uncropped, so zoom in to roughly what an adaptive launcher shows.
const _squareZoom = 1.25;

Future<void> _write(
  String path,
  int size,
  void Function(Canvas, double) paint, {
  double zoom = 1,
  double cornerRadius = 0,
  bool opaque = false,
}) async {
  final recorder = PictureRecorder();
  final canvas = Canvas(recorder);
  if (cornerRadius > 0) {
    canvas.clipRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(0, 0, size.toDouble(), size.toDouble()),
        Radius.circular(size * cornerRadius),
      ),
    );
  }
  canvas
    ..scale(size / _design)
    ..translate(_design / 2, _design / 2)
    ..scale(zoom)
    ..translate(-_design / 2, -_design / 2);
  paint(canvas, _design);
  final image = await recorder.endRecording().toImage(size, size);
  final png = (await image.toByteData(
    format: ImageByteFormat.png,
  ))!.buffer.asUint8List();

  var bytes = png;
  if (opaque) {
    // iOS rejects app icons with an alpha channel, even a fully opaque one.
    final decoded = img.decodePng(png)!.convert(numChannels: 3);
    bytes = img.encodePng(decoded);
  }
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsBytesSync(bytes);
}

void main() {
  testWidgets('generate app icons', (tester) async {
    await tester.runAsync(() async {
      const res = 'android/app/src/main/res';
      // Density → pixels per dp.
      const densities = {
        'mdpi': 1.0,
        'hdpi': 1.5,
        'xhdpi': 2.0,
        'xxhdpi': 3.0,
        'xxxhdpi': 4.0,
      };
      for (final MapEntry(key: density, value: scale) in densities.entries) {
        final dir = '$res/mipmap-$density';
        // Android 8+: adaptive icon layers on the full 108dp canvas.
        final layer = (108 * scale).round();
        await _write('$dir/ic_launcher_background.png', layer, paintBackground);
        await _write('$dir/ic_launcher_foreground.png', layer, paintForeground);
        await _write(
          '$dir/ic_launcher_monochrome.png',
          layer,
          (c, s) => paintForeground(c, s, shadow: false),
        );
        // Android 7: a single 48dp image, shaped by us.
        await _write(
          '$dir/ic_launcher.png',
          (48 * scale).round(),
          paintIcon,
          zoom: _squareZoom,
          cornerRadius: .2,
        );
      }
      File('$res/mipmap-anydpi-v26/ic_launcher.xml')
        ..parent.createSync(recursive: true)
        ..writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon/generate_icons_test.dart -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
''');

      // iOS: every file the app icon set lists, sized from its name.
      const ios = 'ios/Runner/Assets.xcassets/AppIcon.appiconset';
      final name = RegExp(r'Icon-App-([\d.]+)x[\d.]+@(\d)x\.png');
      for (final file in Directory(ios).listSync().whereType<File>()) {
        final match = name.firstMatch(file.uri.pathSegments.last);
        if (match == null) continue;
        final px = (double.parse(match[1]!) * int.parse(match[2]!)).round();
        await _write(file.path, px, paintIcon, zoom: _squareZoom, opaque: true);
      }

      // Play Store listing icon (Play rounds the corners itself).
      await _write(
        'store/play_icon_512.png',
        512,
        paintIcon,
        zoom: _squareZoom,
        opaque: true,
      );
    });
  });
}
